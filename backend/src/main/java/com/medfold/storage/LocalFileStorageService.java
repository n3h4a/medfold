package com.medfold.storage;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.DigestInputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Comparator;
import java.util.HexFormat;
import java.util.UUID;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;

/** Development storage on the local filesystem: {@code <root>/<userId>/<uuid>.<ext>}. */
@Service
public class LocalFileStorageService implements StorageService {

    private static final Logger log = LoggerFactory.getLogger(LocalFileStorageService.class);

    private static final String UUID_PATTERN = "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}";
    private static final Pattern EXTENSION = Pattern.compile("[a-z0-9]{1,10}");
    private static final Pattern KEY = Pattern.compile(UUID_PATTERN + "/" + UUID_PATTERN + "\\.[a-z0-9]{1,10}");

    private final Path root;

    public LocalFileStorageService(StorageProperties properties) {
        this.root = Path.of(properties.root()).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException ex) {
            throw new StorageException("Cannot create storage root " + root, ex);
        }
        log.info("Local file storage at {}", root);
    }

    @Override
    public StoredFile store(UUID userId, InputStream content, String extension) {
        if (extension == null || !EXTENSION.matcher(extension).matches()) {
            throw new IllegalArgumentException("Invalid file extension: " + extension);
        }
        String key = userId + "/" + UUID.randomUUID() + "." + extension;
        Path target = resolve(key);
        Path temp = null;
        try {
            Files.createDirectories(target.getParent());
            // Write to a temp file first and move it into place, so a failed upload never leaves a partial file.
            temp = Files.createTempFile(target.getParent(), ".upload-", ".tmp");
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            long size;
            try (InputStream in = new DigestInputStream(content, digest);
                    OutputStream out = Files.newOutputStream(temp)) {
                size = in.transferTo(out);
            }
            Files.move(temp, target, StandardCopyOption.ATOMIC_MOVE);
            return new StoredFile(key, size, HexFormat.of().formatHex(digest.digest()));
        } catch (IOException ex) {
            throw new StorageException("Failed to store file", ex);
        } catch (NoSuchAlgorithmException ex) {
            throw new IllegalStateException("SHA-256 is not available", ex);
        } finally {
            deleteQuietly(temp);
        }
    }

    @Override
    public Resource load(String key) {
        Path path = resolve(key);
        if (!Files.isRegularFile(path)) {
            throw new StoredFileNotFoundException(key);
        }
        return new FileSystemResource(path);
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException ex) {
            throw new StorageException("Failed to delete file", ex);
        }
    }

    @Override
    public void deleteAllForUser(UUID userId) {
        Path userDir = root.resolve(userId.toString()).normalize();
        if (!userDir.getParent().equals(root) || !Files.isDirectory(userDir)) {
            return;
        }
        try (Stream<Path> paths = Files.walk(userDir)) {
            for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) {
                Files.deleteIfExists(path);
            }
        } catch (IOException ex) {
            throw new StorageException("Failed to delete files of user " + userId, ex);
        }
    }

    /**
     * Turns a key into a path inside the root. Keys are generated by this class, but they are
     * still validated so a corrupted or malicious key can never reach outside the storage root.
     */
    private Path resolve(String key) {
        if (key == null || !KEY.matcher(key).matches()) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root)) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        return path;
    }

    private static void deleteQuietly(Path path) {
        if (path == null) {
            return;
        }
        try {
            Files.deleteIfExists(path);
        } catch (NoSuchFileException ignored) {
            // already moved into place
        } catch (IOException ex) {
            log.warn("Could not remove temporary upload file {}", path, ex);
        }
    }
}
